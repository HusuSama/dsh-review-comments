#!/usr/bin/env node
/**
 * Build the browser half of the file-review bundle.
 *
 * The DSH client module loader expects exactly one classic script per plugin
 * (`window.__ModuleLoader__.load({ id, factory })`). Sources are kept as three
 * concatenated plain-script fragments so they can be authored and reviewed
 * separately; this script stitches them into `client.js`, which is generated
 * and must never be edited by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const ID = 'dsh-review-comments'
const PARTS = ['src/client.core.js', 'src/client.ui.js', 'src/client.apply.js']
/** Host half writes its per-Session git status JSON here; the Client reads the same path. */
const STATUS_DIR = join(here, '.status')

const body = PARTS.map((part) => {
  const source = readFileSync(join(here, part), 'utf8')
  return `    /* ===== ${part} ===== */\n${source.trimEnd()}\n`
}).join('\n')

const output = `/**
 * Generated by build.mjs — do not edit.
 * Sources: ${PARTS.join(', ')}
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(ID)},
  factory(require) {
    const React = require('react')
    const h = React.createElement
    const FR_STATUS_DIR = ${JSON.stringify(STATUS_DIR)}

${body}

    return FR_PLUGIN
  },
})
`

writeFileSync(join(here, 'client.js'), output)
console.log(`client.js: ${output.length} bytes from ${PARTS.length} parts`)
